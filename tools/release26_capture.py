"""Capture actual-engine lighting transitions, then encode the recorded frames."""
from pathlib import Path
import json,os,shutil,subprocess
import qa260
R=Path(__file__).resolve().parents[1]
Q=R/'build/qa26-final';qa260.Q=Q
os.environ['LEO_ASSET_ROOT']=str(R/'build/lighting-content/GameAssets')
ffmpeg=R/'.tools/media/imageio_ffmpeg/binaries/ffmpeg-win-x86_64-v7.1.exe'
for compat in [False,True]:
 renderer='compatibility' if compat else 'forward'
 out=qa260.run('world-'+renderer,'tests/lighting_world_test.gd',compat,extra=['--record-transition'],vehicles=R/'build/lighting-content/GameAssets/vehicles',tracks=R/'build/lighting-content/GameAssets/tracks')
 assert json.loads((out/'world.json').read_text(encoding='utf-8'))['status']=='PASS'
 for folder in out.glob('*-frames'):
  assert folder.resolve().is_relative_to(Q.resolve())
  video=out/(folder.name.removesuffix('-frames')+'-transition.mp4')
  subprocess.run([str(ffmpeg),'-y','-loglevel','error','-framerate','10','-i',str(folder/'%04d.png'),'-c:v','libx264','-crf','20','-pix_fmt','yuv420p',str(video)],check=True)
  assert video.stat().st_size>1000
  shutil.copy2(folder/'capture.json',video.with_suffix('.json'))
  # Only discard frames generated by this script after the clip is encoded.
  for p in folder.glob('*.png'):p.unlink()
 print('TRANSITIONS_ENCODED',renderer,flush=True)
